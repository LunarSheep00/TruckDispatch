def get_dynamic_tasks():
    """返回带到达时间（分钟）的动态任务列表。
    任务分 5 批到达，每批间隔 30 分钟，模拟真实港口作业场景。
    格式: (id, start, end, arrival_time_min)

    批次分布（80 个任务，每批 16 个）:
      t=0    第一批 16 个（初始作业高峰）
      t=30   第二批 16 个
      t=60   第三批 16 个
      t=90   第四批 16 个
      t=120  第五批 16 个（最后激增）
    """
    base = get_tasks()
    schedule = [0, 30, 60, 90, 120]
    tasks_per_batch = 16
    dynamic = []
    for i, (tid, s, e) in enumerate(base):
        batch_idx = i // tasks_per_batch
        arrival = schedule[min(batch_idx, len(schedule) - 1)]
        dynamic.append((tid, s, e, arrival))
    return dynamic
